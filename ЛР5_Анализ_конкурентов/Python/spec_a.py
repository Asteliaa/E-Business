def build():
    rows = A.build()
    ev = A.evidence(rows)
    s = Spec("Шаблон_классификации_компаний_по_уровням_конкуренции.xlsx", OUT_NAME)
    s.extra["author"] = WHO
    s.extra["reparse_xlookup"] = True
    s.extra["title"] = "Классификация компаний по уровням конкуренции: NotaCode"
    # --- исправления проверки данных
    s.dv_list(SH1, "I4:I103", "='08_Справочники'!$C$2:$C$4")
    s.dv_whole(SH2, "G4:G303", 1, 5)
    s.dv_list(SH4, "S4:S103", "='08_Справочники'!$B$2:$B$6")
    # --- 01_Компании
    for i, r in enumerate(rows):
        co = r["co"]
        rw = 4 + i
        hyp = [A.LEVELS[0], A.LEVELS[1], A.LEVELS[2], A.LEVELS[3]][co["hyp"]]
        comment = "Источник обнаружения: " + co["disc"] + "."
        if co["bc"]:
            comment += " Переходит в части B и C (одна из семи компаний анализа цифрового товара и бизнес-модели)."
        s.row(SH1, rw, "B", [co["name"], co["dom"], co["market"], co["ctype"], co["product"], co["seg"], hyp, co["prio"], WHO,
                              A.STATUS_LOW if r["lim"] == "Недостаточно данных" else A.STATUS_OK])
        s.date(SH1, f"L{rw}")
        s.w(SH1, f"M{rw}", comment)
    # --- 02_Доказательства
    for i, e in enumerate(ev):
        rw = 4 + i
        cid, sect, url, fact, typ, strength, date, concl, auth, shot, comm = e
        s.w(SH2, f"A{rw}", cid)
        s.w(SH2, f"C{rw}", sect)
        s.w(SH2, f"D{rw}", url)
        s.w(SH2, f"E{rw}", fact)
        s.w(SH2, f"F{rw}", typ)
        s.w(SH2, f"G{rw}", strength)
        s.date(SH2, f"H{rw}")
        s.w(SH2, f"I{rw}", concl)
        s.w(SH2, f"J{rw}", auth)
        s.w(SH2, f"K{rw}", shot)
        s.w(SH2, f"L{rw}", comm)
    # --- 04_Оценка
    ev_count = {}
    for e in ev:
        ev_count[e[0]] = ev_count.get(e[0], 0) + 1
    for i, r in enumerate(rows):
        co = r["co"]
        rw = 4 + i
        for j, v in enumerate(r["sc"]):
            if v is not None:
                s.wrc(SH4, rw, 4 + j, v)
        text = A.rationale(co, r["sc"], r["calc"], r["final"])
        refs = f"02_Доказательства: {ev_count.get(co['id'], 0)} строк (ID {co['id']})"
        if r["corr"]:
            s.w(SH4, f"Q{rw}", r["corr"][0])
            text = "Экспертная корректировка: " + r["corr"][1] + " " + text
            refs += "; ЛР1 табл. 44; ЛР2-3 (маркетплейсы); Вордстат 29.08-27.09.2026"
        s.w(SH4, f"S{rw}", A.STATUS_LOW if r["lim"] == "Недостаточно данных" else A.STATUS_OK)
        s.w(SH4, f"T{rw}", text)
        s.w(SH4, f"U{rw}", refs)
        s.date(SH4, f"V{rw}")
        # 07_Карта
        s.w(SH7, f"H{rw}", f"Уверенность: {r['conf']}; заполнено критериев: {r['nfilled']} из 10")
        s.w(SH7, f"I{rw}", f"02_Доказательства: {ev_count.get(co['id'], 0)} строк")
    # --- Д-6: SUMPRODUCT строки на столбец давал #ЗНАЧ!; явная сумма произведений
    wsum = "+".join(f"{col}{{r}}*'03_Критерии'!$E${4 + i}" for i, col in enumerate("DEFGHIJKLM"))
    for rw in range(4, 104):
        s.fx(SH4, f"N{rw}", f"=IF(COUNTA(D{rw}:M{rw})=0,\"\",(" + wsum.format(r=rw) + ")/SUM('03_Критерии'!$E$4:$E$13))")
    # --- Д-8: нули вместо пустых значений XLOOKUP и зона карты при недостатке данных
    def xl(sheet, col, key, rng):
        return f"=IFERROR(IF(XLOOKUP({key},'{sheet}'!$A$4:$A$103,'{sheet}'!${rng}$4:${rng}$103)=\"\",\"\",XLOOKUP({key},'{sheet}'!$A$4:$A$103,'{sheet}'!${rng}$4:${rng}$103)),\"\")"
    for rw in range(4, 104):
        s.fx(SH4, f"B{rw}", xl("01_Компании", "B", f"A{rw}", "B"))
        s.fx(SH4, f"C{rw}", xl("01_Компании", "C", f"A{rw}", "C"))
        s.fx(SH7, f"B{rw}", xl("04_Оценка", "B", f"A{rw}", "B"))
        s.fx(SH7, f"J{rw}", xl("01_Компании", "I", f"A{rw}", "I"))
        s.fx(SH7, f"K{rw}", xl("04_Оценка", "S", f"A{rw}", "S"))
        s.fx(SH7, f"G{rw}", f'=IF(E{rw}="","",IF(OR(F{rw}="Недостаточно данных",C{rw}="",D{rw}=""),"Нет данных",IF(AND(C{rw}>=4,D{rw}>=4),"Ядро прямой конкуренции",IF(AND(C{rw}>=3,D{rw}>=3),"Близкая альтернатива",IF(C{rw}>=3,"Функциональный заменитель",IF(D{rw}>=3,"Аудиторное пересечение","Периферия"))))))')
    # --- исправление топ-10 при равных баллах (Д-4)
    pos = "AGGREGATE(15,6,(ROW('04_Оценка'!$N$4:$N$103)-ROW('04_Оценка'!$N$4)+1)/('04_Оценка'!$N$4:$N$103=D{r}),COUNTIF($D$19:D{r},D{r}))"
    for rw in range(19, 29):
        p = pos.format(r=rw)
        s.fx(SH6, f"B{rw}", f"=IF(D{rw}=\"\",\"\",INDEX('04_Оценка'!$B$4:$B$103,{p}))")
        s.fx(SH6, f"C{rw}", f"=IF(D{rw}=\"\",\"\",INDEX('04_Оценка'!$C$4:$C$103,{p}))")
        s.fx(SH6, f"E{rw}", f"=IF(D{rw}=\"\",\"\",INDEX('04_Оценка'!$R$4:$R$103,{p}))")
        s.fx(SH6, f"F{rw}", f"=IF(D{rw}=\"\",\"\",INDEX('04_Оценка'!$T$4:$T$103,{p}))")
    # --- автоподбор высоты строк
    s.fit(SH1, "A4:M25")
    s.fit(SH2, f"A4:L{3 + len(ev)}")
    s.fit(SH4, "A4:V25")
    s.fit(SH7, "A4:K25")
    s.fit(SH6, "A19:F28")
    # --- журнал
    s.new_sheets.append(dict(name="09_Журнал", title="Журнал рабочей копии: исправления шаблона, шкала, правила баллов, незаполненные данные",
                             header=["Раздел", "Код", "Содержание"], rows=journal_rows(rows, ev), widths=[34, 8, 150]))
    out = os.path.join(C.DATA, "spec_a.json")
    s.to_json(out)
    return rows, ev, out


if __name__ == "__main__":
    rows, ev, out = build()
    print(out, len(ev))
