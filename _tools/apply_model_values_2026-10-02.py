# Модельные значения для оставшихся пропусков (ЛР2-3, ЛР4, ЛР7). Все значения - оценки по допущениям, не данные источников.
import re

RATE = 3.03


def fmt(x, n=0):
    return f"{x:,.{n}f}".replace(',', ' ').replace('.', ',')


def rd(p):
    return open(p, encoding='utf-8').read()


def wr(p, t):
    open(p, 'w', encoding='utf-8').write(t)


def rep(t, a, b):
    assert t.count(a) == 1, (a[:60], t.count(a))
    return t.replace(a, b)


# ---------- CPC по запросам (модель)
queries = [("uml", 701, 1.00), ("bpmn", 495, 1.80), ("idef0", 115, 0.90), ("plantuml", 205, 1.10), ("диаграмма онлайн", 301, 1.30)]
CTR = 0.04
CONV = 0.03
rows = []
for q, vol, cpc in queries:
    clicks = vol * CTR
    budget = clicks * cpc * RATE
    cac = cpc / CONV * RATE
    rows.append(f"| {q} | {vol} | {str(cpc).replace('.', ',')} | {fmt(cpc * RATE, 2)} | {fmt(clicks, 0)} | {fmt(budget, 0)} | {fmt(cac, 0)} |")
cpc_table = "\n".join(rows)
tot_budget = sum(v * CTR * c * RATE for _, v, c in queries)
tot_clicks = sum(v * CTR for _, v, _ in queries)

p = 'ЛР2-3_Объем_рынка/ОТЧЕТ.md'
t = rd(p)
if 'Таблица 97 – Модельная оценка' not in t:
    t = t.rstrip('\n') + f"""

Реальные ставки по запросам ядра не получены, поэтому для планирования принята модельная оценка: ставка выбирается внутри диапазона 0,90–4,80 USD для B2B SaaS [40] с учётом того, что запросы учебные и ставки для них ниже средних по SaaS; CTR объявления принят равным 4 %, конверсия клика в оплату 3 %. Модель служит для оценки порядка величин и заменяется данными прогноза Директа после создания кампании.

Таблица 97 – Модельная оценка стоимости привлечения по запросам (допущения)

| Запрос | Запросов в месяц (Вордстат, сентябрь 2026) | Ставка, USD за клик | Ставка, BYN за клик | Кликов в месяц при CTR 4 % | Бюджет на все клики, BYN в месяц | Цена платящего клиента, BYN |
|---|---|---|---|---|---|---|
{cpc_table}

Итого по пяти запросам: около {fmt(tot_clicks)} кликов и {fmt(tot_budget)} BYN в месяц, что при конверсии 3 % даёт около {fmt(tot_clicks * CONV, 1)} платящего клиента в месяц. Цена платящего клиента ({fmt(0.9 / CONV * RATE)}–{fmt(1.8 / CONV * RATE)} BYN) сопоставима с выручкой первого года (117,63 BYN после комиссии), поэтому платный поиск не окупается и допустим только для проверки гипотез небольшим бюджетом.
"""
    wr(p, t)
    print('ЛР2-3 ok')

# ---------- доля Беларуси (модель)
GLOBAL_USERS = 5500.0   # млн интернет-пользователей в мире (допущение)
BY_USERS = 8.47          # млн, DataReportal
base_share = BY_USERS / GLOBAL_USERS * 100
share = round(base_share * 2, 2)   # поправка x2: учебная и ИТ-аудитория
doms = [("lucid.app", 13.38), ("drawio.com", 7.19), ("mermaid.ai", 6.27), ("whimsical.com", 4.27), ("eraser.io", 2.18)]
drow = []
tot = 0
for d, v in doms:
    m = v * 1e6 / 3
    by = m * share / 100
    tot += by
    drow.append(f"| {d} | {fmt(m)} | {fmt(by)} |")
drows = "\n".join(drow)

p = 'ЛР4_Пять_сил_Портера/ОТЧЕТ.md'
t = rd(p)
if 'Таблица 68 – Модельная оценка' not in t:
    t = t.rstrip('\n') + f"""

Доля Беларуси в трафике доменов в пробном тарифе недоступна, поэтому для расчёта индекса барьеров принята модельная оценка. Базовая доля равна отношению числа интернет-пользователей Беларуси (8,47 млн, по данным ЛР2-3 [8]) к числу пользователей мира (около 5 500 млн, допущение): {str(round(base_share, 2)).replace('.', ',')} %. Для учебной и ИТ-аудитории вводится поправка 2: принятая доля равна {str(share).replace('.', ',')} %. Оценка не заменяет данных Similarweb и подлежит замене после получения доли Беларуси.

Таблица 68 – Модельная оценка визитов из Беларуси (допущение: доля {str(share).replace('.', ',')} %)

| Домен | Визитов в месяц, мир (среднее за 3 месяца) | Визитов в месяц из Беларуси, оценка |
|---|---|---|
{drows}

Суммарно по пяти доменам из Беларуси приходит около {fmt(tot)} визитов в месяц, что сопоставимо с поисковым спросом ядра (около 1 800 запросов в месяц по Вордстату); рынок не пустой, но невелик.
"""
    wr(p, t)
    print('ЛР4 ok')

