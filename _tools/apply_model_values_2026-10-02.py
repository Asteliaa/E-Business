    t = rep(t, "| 5 | 🔲 ДОСНЯТЬ: доля Беларуси в Similarweb, Директ и LinkedIn Ad Library, индекс барьеров ЛР4 | Пробный доступ открывает только Worldwide; кабинет Директа пуст; частично собрано (приложение 8) |",
            "| 5 | Доля Беларуси в Similarweb, CPC Директа, LinkedIn Ad Library, индекс барьеров ЛР4 | Заменены модельными оценками (приложение 10); реальные данные недоступны в пробном тарифе и пустом кабинете |")
    wr(p, t)
    print('ЛР7 ok')
