# Обновляет разделы «Выводы» с учётом данных 02.10.2026. Повторный запуск безопасен.
import re


def rd(p):
    return open(p, encoding='utf-8').read()


def wr(p, t):
    open(p, 'w', encoding='utf-8').write(t)


def rep(t, a, b):
    if b in t:
        return t
    assert t.count(a) == 1, (a[:60], t.count(a))
    return t.replace(a, b)


def add_item(t, marker_start, text):
    """Добавляет последний пункт в раздел «Выводы», если его ещё нет."""
    m = re.search(r'^## Выводы\n(.*?)(?=^## )', t, re.M | re.S)
    block = m.group(1)
    if text[:40] in block:
        return t
    nums = re.findall(r'^(\d+)\. ', block, re.M)
    n = int(nums[-1]) + 1
    new_block = block.rstrip('\n') + f"\n\n{n}. {text}\n\n"
    return t[:m.start(1)] + new_block + t[m.end(1):]


