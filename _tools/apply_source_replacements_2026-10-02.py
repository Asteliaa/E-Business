import re


def rd(p):
    return open(p, encoding='utf-8').read()


def wr(p, t):
    open(p, 'w', encoding='utf-8').write(t)


def rep(t, a, b, must=True):
    n = t.count(a)
    if n == 0:
        if must and b not in t:
            raise SystemExit('нет фрагмента: ' + a[:70])
        return t
    assert n == 1, (a[:60], n)
    return t.replace(a, b)


def fmt(x):
    return f"{x:,.0f}".replace(',', ' ')


