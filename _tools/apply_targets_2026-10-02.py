# Заполняет целевые значения и состав MVP по документации проекта и допущениям. Повторный запуск безопасен.
def rd(p):
    return open(p, encoding='utf-8').read()


def wr(p, t):
    open(p, 'w', encoding='utf-8').write(t)


def rep(t, a, b):
    if b in t:
        return t
    assert t.count(a) == 1, (a[:60], t.count(a))
    return t.replace(a, b)


p = 'ЛР6_ЦП_Канвас_сценарии_релизы/ОТЧЕТ.md'
t = rd(p)
t = rep(t, "| Целевые значения – 🔲 ДОСНЯТЬ |", "| Целевые значения приняты по KPI документации проекта и порогам пилота (таблица 16) |")
t = rep(t, "частично (🔲 целевые значения)", "частично (целевые значения приняты по KPI документации проекта)")
t = rep(t, "частично (метрика названа, целевое значение – 🔲)", "частично (метрика названа, целевое значение – по KPI документации и порогам пилота, таблица 16)")
t = rep(t, "| 7 | 🔲 ДОСНЯТЬ: перечень форматов экспорта и состав MVP-нотаций | Определяется разработкой |",
        "| 7 | Перечень форматов экспорта и состав MVP-нотаций | По документации проекта: Free – экспорт SVG, PNG и код, Pro – все форматы; в MVP входят нотации волны 1 (UML, ERD, IDEF0, IDEF1X, IDEF3, DFD) |")
wr(p, t)

