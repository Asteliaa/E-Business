t = rep(t, "частично (пороги и бюджет – 🔲)", "частично (пороги и бюджет – допущения приложения 9)")
t = rep(t, "🔲 ДОСНЯТЬ: скорость и доступность",
        "целевые значения скорости и доступности – допущения: загрузка редактора не более 3 секунд, доступность не ниже 99 % в месяц (оценка, измерением не подтверждена)")
